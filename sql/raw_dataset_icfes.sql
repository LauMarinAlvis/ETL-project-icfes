CREATE DATABASE IF NOT EXISTS icfes_db;
USE icfes_db;

DROP TABLE IF EXISTS raw_icfes_historico;

CREATE TABLE raw_icfes_historico (
    id_raw BIGINT AUTO_INCREMENT PRIMARY KEY,
    
    -- Llave de Negocio y Identificación
    ESTU_CONSECUTIVO VARCHAR(100),
    PERIODO VARCHAR(20),
    
    -- Ubicación
    ESTU_DEPTO_RESIDE VARCHAR(100),
    ESTU_MCPIO_RESIDE VARCHAR(100),
    
    -- Colegio
    COLE_COD_ICFES VARCHAR(100),
    COLE_NOMBRE_ESTABLECIMIENTO VARCHAR(255),
    COLE_NATURALEZA VARCHAR(100),
    COLE_CALENDARIO VARCHAR(50),
    COLE_AREA_UBICACION VARCHAR(100),
    
    -- Variables Socioeconómicas
    FAMI_ESTRATOVIVIENDA VARCHAR(100),
    FAMI_EDUCACIONPADRE VARCHAR(255),
    FAMI_EDUCACIONMADRE VARCHAR(255),
    FAMI_TIENEINTERNET VARCHAR(50),
    FAMI_TIENECOMPUTADOR VARCHAR(50),
    FAMI_PERSONASHOGAR VARCHAR(50),
    ESTU_NSE_INDIVIDUAL VARCHAR(20),
    ESTU_INSE_INDIVIDUAL VARCHAR(20),
    
    -- Puntajes y Métricas
    PUNT_GLOBAL VARCHAR(20),
    PUNT_MATEMATICAS VARCHAR(20),
    PUNT_LECTURA_CRITICA VARCHAR(20),
    PUNT_NATURALES VARCHAR(20),
    PUNT_SOCIALES_CIUDADANAS VARCHAR(20),
    PUNT_INGLES VARCHAR(20),
    
    -- Fecha de ingestión para auditoría
    fecha_ingesta TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);