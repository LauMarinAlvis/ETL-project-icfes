USE icfes_db;

CREATE TABLE IF NOT EXISTS Dim_Colegio (
    id_colegio INT PRIMARY KEY AUTO_INCREMENT,
    COLE_COD_ICFES VARCHAR(50),
    COLE_NOMBRE_ESTABLECIMIENTO VARCHAR(255),
    COLE_NATURALEZA VARCHAR(100),
    COLE_CALENDARIO VARCHAR(50),
    COLE_AREA_UBICACION VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS Dim_Socioeconomica (
    id_socioeconomico INT PRIMARY KEY AUTO_INCREMENT,
    FAMI_ESTRATOVIVIENDA VARCHAR(100),
    FAMI_EDUCACIONPADRE VARCHAR(255),
    FAMI_EDUCACIONMADRE VARCHAR(255),
    FAMI_TIENEINTERNET VARCHAR(50),
    FAMI_TIENECOMPUTADOR VARCHAR(50),
    FAMI_PERSONASHOGAR VARCHAR(50),
    ESTU_NSE_INDIVIDUAL VARCHAR(10)
);

CREATE TABLE IF NOT EXISTS Dim_Tiempo (
    id_tiempo INT PRIMARY KEY AUTO_INCREMENT,
    PERIODO VARCHAR(50),
    ANIO INT,
    SEMESTRE INT
);

CREATE TABLE IF NOT EXISTS Dim_Ubicacion (
    id_ubicacion INT PRIMARY KEY AUTO_INCREMENT,
    ESTU_DEPTO_RESIDE VARCHAR(100),
    ESTU_MCPIO_RESIDE VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS Fact_ResultadosSaber11 (
    PUNT_GLOBAL INT,
    PUNT_MATEMATICAS INT,
    PUNT_LECTURA_CRITICA INT,
    PUNT_NATURALES INT,
    PUNT_SOCIALES_CIUDADANAS INT,
    PUNT_INGLES INT,
    ESTU_INSE_INDIVIDUAL FLOAT,
    id_resultado BIGINT PRIMARY KEY AUTO_INCREMENT,
    id_colegio INT NOT NULL,
    id_socioeconomico INT NOT NULL,
    id_tiempo INT NOT NULL,
    id_ubicacion INT NOT NULL,
    BK_ESTU_CONSECUTIVO VARCHAR(100),
    CONSTRAINT fk_fact_colegio FOREIGN KEY (id_colegio) REFERENCES Dim_Colegio(id_colegio),
    CONSTRAINT fk_fact_socioeconomico FOREIGN KEY (id_socioeconomico) REFERENCES Dim_Socioeconomica(id_socioeconomico),
    CONSTRAINT fk_fact_tiempo FOREIGN KEY (id_tiempo) REFERENCES Dim_Tiempo(id_tiempo),
    CONSTRAINT fk_fact_ubicacion FOREIGN KEY (id_ubicacion) REFERENCES Dim_Ubicacion(id_ubicacion)
);